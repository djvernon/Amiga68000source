plotpixel
	move.b	d0,d6
	and.w	#%111,d6
	move.w	#%1111111101111111,d4
	lsr	d6,d4
	move.b	d4,d5
	not.b	d5
	lsr	#3,d0
	lsl	#1,d1
	add.w	(a0,d1.w),d0
planeloop
	move.l	(a1)+,a2
	move.b	(a2,d0.w),d6
	and.b	d4,d6
	btst	#0,d2
	beq	nextplane
	or	d5,d6
nextplane
	move.b	d6,(a2,d0.w)
	ror	#1,d2
	dbra	d3,planeloop
	rts

calcytable
	sub.w	#1,d1
	moveq	#0,d2
	lsr	#3,d0
ytabloop
	move.w	d2,(a0)+
	add.w	d0,d2
	dbra	d1,ytabloop
	rts

